const CALLING_CODE_OVERRIDES = Object.freeze({
  AX: 358,
  AG: 1268,
  BA: 387,
  RE: 262,
  ST: 239,
  GS: 500,
  TT: 1868,
  TC: 1649,
  WF: 681,
});

const regionsByCountryCode = new Map(
  regionCountries.map((country) => [country.countryShortCode, country.regions.map((region) => region.name)])
);

function getCountryCode(countryName) {
  if (!COUNTRY_SET.has(countryName)) return null;
  return COUNTRY_CODE_ALIASES[countryName] || countryMetadata.getCountryCode(countryName) || null;
}

function getCountryRegions(countryName) {
  const countryCode = getCountryCode(countryName);
  return countryCode ? regionsByCountryCode.get(countryCode) || [] : [];
}

function getCountryCallingCode(countryName) {
  const countryCode = getCountryCode(countryName);
  const callingCode = countryCode && (
    CALLING_CODE_OVERRIDES[countryCode] ||
    countryMetadata.countries[countryCode]?.phone?.[0]
  );
  return callingCode ? `+${callingCode}` : '';
}

function normalizePhoneNumber(value, countryName) {
  const countryCode = getCountryCode(countryName);
  if (!countryCode || typeof value !== 'string' || !value.trim()) return null;

  const phoneNumber = parsePhoneNumberFromString(value, countryCode);
  if (
    !phoneNumber ||
    !phoneNumber.isValid() ||
    phoneNumber.countryCallingCode !== getCountryCallingCode(countryName).slice(1)
  ) {
    return null;
  }
  return phoneNumber.number;
}

function isRegionForCountry(countryName, regionName) {
  const regions = getCountryRegions(countryName);
  return regions.length ? regions.includes(regionName) : regionName === '';
}

function isCountry(value) {
  return typeof value === 'string' && COUNTRY_SET.has(value);
}

function isGender(value) {
  return typeof value === 'string' && GENDER_SET.has(value);
}

module.exports = {
  COUNTRIES,
  GENDERS,
  getCountryCallingCode,
  getCountryRegions,
  normalizePhoneNumber,
  isCountry,
  isGender,
  isRegionForCountry,
};
